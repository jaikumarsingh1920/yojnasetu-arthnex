def sanitize_value(val):
    """Replaces inappropriate sentinels (0, 0.0, 0%, UNKNOWN, N/A, etc.) with None or clean string."""
    if val is None:
        return ""
    v_str = str(val).strip()
    if v_str in ["0", "0.0", "0%", "0.0%", "UNKNOWN", "N/A", "NA", "NULL", "None", "-"]:
        return ""
    return v_str


