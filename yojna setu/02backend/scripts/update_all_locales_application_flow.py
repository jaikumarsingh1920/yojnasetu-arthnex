def update_all_locales():
    for lang, translations in HOW_TO_APPLY_TRANSLATIONS.items():
        file_path = os.path.join(LOCALES_DIR, f"{lang}.json")
        if not os.path.exists(file_path):
            print(f"Skipping missing locale: {file_path}")
            continue

        with open(file_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        data["howToApply"] = translations
        if "recommendations" not in data:
            data["recommendations"] = {}
        data["recommendations"]["viewScheme"] = RECOMMENDATION_EXTRA_KEYS.get(lang, {}).get("viewScheme", "View Scheme")

        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)

        print(f"Updated {lang}.json successfully with howToApply namespace.")

if __name__ == "__main__":
    update_all_locales()
